import type { SVGProps } from "react";

/*
 * A single outline icon set (24px grid, 1.75 stroke, round caps) shared across
 * the storefront so every icon reads as one family. Each icon inherits color
 * from `currentColor` and accepts standard SVG props (e.g. `className`).
 */

/** Base wrapper applying the shared stroke style to a set of children paths. */
function Icon({ children, ...props }: SVGProps<SVGSVGElement>) {
  return (
    <svg
      width="24"
      height="24"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  );
}

